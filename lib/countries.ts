// Country list with flag emojis and names in multiple languages
// Flags use Unicode regional indicator symbols (works on iOS/Android)

export interface Country {
  code: string;        // ISO 3166-1 alpha-2
  flag: string;        // Unicode flag emoji
  name: {              // Names in all supported languages
    en: string;
    pt: string;
    fr: string;
    es: string;
    'es-US': string;
    zh: string;
    ja: string;
    ko: string;
    vi: string;
    tl: string;
    ar: string;
    ru: string;
    hi: string;
    bn: string;
    ln: string;
  };
}

// Convert country code to flag emoji
export function countryCodeToFlag(code: string): string {
  return code
    .toUpperCase()
    .split('')
    .map(char => String.fromCodePoint(0x1F1E6 + char.charCodeAt(0) - 65))
    .join('');
}

