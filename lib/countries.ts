/**
 * Get country name by language
 */
export function getCountryName(country: Country, lang: string): string {
  const langKey = lang as keyof typeof country.name;
  return country.name[langKey] || country.name.en;
}

/**
 * Search countries by name (in any language)
 */
export function searchCountries(query: string, lang: string): Country[] {
  const lowerQuery = query.toLowerCase();
  return COUNTRIES.filter(country => {
    const name = getCountryName(country, lang).toLowerCase();
    return name.includes(lowerQuery) || country.code.toLowerCase().includes(lowerQuery);
  });
}
