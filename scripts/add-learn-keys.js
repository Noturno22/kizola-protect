// Process each language file
const langs = fs.readdirSync(TRANSLATIONS_DIR)
  .filter(f => f.endsWith('.json') && f !== 'en.json' && f !== 'en-articles-reference.json');

let totalAdded = 0;

for (const langFile of langs) {
  const lang = langFile.replace('.json', '');
  const filePath = path.join(TRANSLATIONS_DIR, langFile);
  
  try {
    const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));
    let added = 0;
    
    // Add learn.* keys
    if (!data.learn) data.learn = {};
    const translations = TRANSLATIONS[lang] || TRANSLATIONS['en'];
    
    for (const [key, value] of Object.entries(NEW_LEARN_KEYS)) {
      if (!data.learn[key]) {
        data.learn[key] = translations[key] || value;
        added++;
      }
    }
    
    // Add dashboard.sort key
    if (!data.dashboard) data.dashboard = {};
    if (!data.dashboard.sort) {
      data.dashboard.sort = translations.sort || NEW_DASHBOARD_KEYS.sort;
      added++;
    }
    
    if (added > 0) {
      fs.writeFileSync(filePath, JSON.stringify(data, null, 2) + '\n');
      console.log(`✅ ${lang}: added ${added} keys`);
      totalAdded += added;
    } else {
      console.log(`⏭️  ${lang}: already complete`);
    }
  } catch (err) {
    console.error(`❌ ${lang}: ${err.message}`);
  }
}

console.log(`\n📊 Total: ${totalAdded} keys added across ${langs.length} languages`);
